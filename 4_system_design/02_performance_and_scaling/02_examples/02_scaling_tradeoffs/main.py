"""
Пример 02: горизонтальное масштабирование и предел закона Амдала.

Симулирует прирост throughput при добавлении узлов (горизонтальное
масштабирование) для задачи, часть работы которой обязательно
последовательна (координация, агрегация результата) и не ускоряется
добавлением узлов. Показывает: (1) сначала прирост почти линейный,
(2) при росте числа узлов прирост выходит на плато, определяемое
долей последовательной части, независимо от того, сколько узлов
добавлено сверху.

Запуск: python3 ./02_examples/02_scaling_tradeoffs/main.py
"""

from __future__ import annotations

import math


def amdahl_speedup(parallel_fraction: float, n_nodes: int) -> float:
    """speedup(N) = 1 / ((1 - p) + p / N)"""
    sequential_fraction = 1.0 - parallel_fraction
    return 1.0 / (sequential_fraction + parallel_fraction / n_nodes)


def main() -> None:
    print("--- Пример: закон Амдала при горизонтальном масштабировании ---")

    # 90% работы параллелится, 10% - неизбежно последовательная часть
    # (например, финальная агрегация ответов со всех узлов).
    p = 0.9
    node_counts = [1, 2, 4, 8, 16, 32, 64, 128]

    print(f"Доля параллелимой работы p={p} (10% всегда последовательно)\n")
    header_tp = "throughput при base=100 req/s"
    print(f"{'узлов':>6} | {'speedup':>8} | {header_tp:>30}")
    print("-" * 52)

    base_throughput = 100.0
    prev_speedup = None
    for n in node_counts:
        speedup = amdahl_speedup(p, n)
        throughput = base_throughput * speedup
        print(f"{n:6d} | {speedup:8.2f}x | {throughput:30.1f} req/s")
        if prev_speedup is not None:
            # Прирост speedup от удвоения узлов должен убывать по мере
            # роста N - это и есть выход на плато закона Амдала.
            growth = speedup - prev_speedup
        prev_speedup = speedup

    theoretical_max = 1.0 / (1.0 - p)
    print(
        f"\nТеоретический предел speedup при N -> бесконечность: "
        f"{theoretical_max:.1f}x"
    )

    # Прирост speedup от удвоения узлов у самого старта (1 -> 2) сравниваем
    # с приростом от такого же удвоения у верхней границы (64 -> 128):
    # по мере роста N одинаковое по кратности удвоение даёт всё меньший
    # абсолютный прирост - это и есть выход на плато закона Амдала.
    growth_1_to_2 = amdahl_speedup(p, 2) - amdahl_speedup(p, 1)
    growth_64_to_128 = amdahl_speedup(p, 128) - amdahl_speedup(p, 64)

    assert math.isclose(theoretical_max, 10.0)
    assert growth_64_to_128 < growth_1_to_2, (
        "удвоение узлов у верхней границы должно давать меньший прирост"
    )

    print(
        f"\nУдвоение узлов у старта (1 -> 2) даёт прирост "
        f"{growth_1_to_2:.2f}x, а такое же по кратности удвоение у верхней "
        f"границы (64 -> 128) — всего {growth_64_to_128:.2f}x. Основная "
        f"часть выигрыша уже выбрана, а оставшиеся 10% последовательной "
        f"работы ограничивают предел сверху вне зависимости от числа узлов. "
        f"Дальнейшее горизонтальное масштабирование малоэффективно, пока не "
        f"уменьшена последовательная доля (например, убрана "
        f"координация/агрегация из критического пути)."
    )


if __name__ == "__main__":
    main()
