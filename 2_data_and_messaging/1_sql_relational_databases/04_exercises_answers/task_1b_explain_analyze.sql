-- Решение 1b: прочитать и объяснить план EXPLAIN ANALYZE

EXPLAIN ANALYZE
SELECT * FROM orders
WHERE order_date >= CURRENT_DATE - INTERVAL '7 days';

-- Типичный вывод ДО индекса:
--
-- Seq Scan on orders  (cost=0.00..4832.00 rows=1972 width=42)
--                      (actual time=0.020..35.100 rows=1980 loops=1)
--   Filter: (order_date >= (CURRENT_DATE - '7 days'::interval))
--   Rows Removed by Filter: 198020
-- Planning Time: 0.150 ms
-- Execution Time: 35.180 ms

-- 1. Планировщик выбирает Seq Scan, потому что order_date не индексирован --
--    у него просто нет другого пути доступа, кроме как прочитать таблицу
--    целиком и отфильтровать построчно. Даже если бы индекс был, при
--    условии "последние 7 дней из ~700 дней разброса" в выборку попадает
--    около 1/100 строк (~2000 из 200000) -- это уже достаточно
--    селективно, чтобы Index Scan/Bitmap Heap Scan оказался дешевле
--    полного скана.
--
-- 2. cost=0.00..4832.00 -- условные единицы стоимости по внутренней модели
--    планировщика: 0.00 -- цена "до первой строки" (для Seq Scan это
--    почти сразу), 4832.00 -- цена "до последней строки" (нужно пройти
--    всю таблицу). rows=1972 в cost-части -- ОЦЕНКА планировщика по
--    статистике (гистограмма order_date в pg_statistic). actual
--    time=0.020..35.100 -- реальное время в миллисекундах до первой и до
--    последней строки. rows=1980 в actual-части -- фактическое число
--    подходящих строк. Оценка (1972) и факт (1980) здесь ПОЧТИ совпадают --
--    значит, статистика по таблице свежая (ANALYZE выполнялся после
--    последней существенной вставки/удаления данных). Если бы расхождение
--    было большим (например, оценка 10, факт 50000), это был бы прямой
--    сигнал сделать ANALYZE orders.

CREATE INDEX idx_orders_order_date ON orders (order_date);
ANALYZE orders;

EXPLAIN ANALYZE
SELECT * FROM orders
WHERE order_date >= CURRENT_DATE - INTERVAL '7 days';

-- После индекса план обычно меняется на:
--
-- Bitmap Heap Scan on orders (cost=45.00..980.00 rows=1972 ...)
--   Recheck Cond: (order_date >= ...)
--   ->  Bitmap Index Scan on idx_orders_order_date (cost=0.00..44.50 ...)
--         Index Cond: (order_date >= ...)
--
-- Bitmap Heap Scan, а не простой Index Scan, потому что совпадений
-- довольно много (~2000 строк) -- планировщик решает, что дешевле
-- сначала собрать битовую карту нужных страниц таблицы по индексу, а
-- затем прочитать эти страницы последовательно, чем прыгать по диску
-- отдельным Index Scan на каждую строку. Итоговое Execution Time при
-- этом заметно меньше, чем при Seq Scan.
