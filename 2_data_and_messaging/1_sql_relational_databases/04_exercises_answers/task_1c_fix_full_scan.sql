-- Решение 1c: найти и исправить запрос с полным сканированием
-- из-за функции над столбцом

EXPLAIN ANALYZE
SELECT * FROM customers WHERE lower(email) = 'customer1500@example.com';
-- Даже при наличии idx_customers_email (обычный индекс на email) план
-- всё равно Seq Scan.

-- Почему обычный индекс не используется: индекс idx_customers_email
-- хранит исходные значения столбца email "как есть", а не результат
-- применения lower() к ним. Планировщик не может "заглянуть внутрь"
-- индекса и понять, что lower(email) для какой-то строки равно нужной
-- строке -- он либо ищет по индексу ЗНАЧЕНИЕ email, либо не использует
-- этот индекс вовсе. Здесь запрос сравнивает не email, а lower(email) --
-- это другое выражение, для которого обычного индекса просто нет.

-- Исправление: функциональный индекс -- строится не по самому столбцу,
-- а по результату выражения lower(email); тогда индекс и запрос "говорят
-- об одном и том же" выражении, и планировщик может им воспользоваться.
CREATE INDEX idx_customers_email_lower ON customers (lower(email));

EXPLAIN ANALYZE
SELECT * FROM customers WHERE lower(email) = 'customer1500@example.com';
-- После создания функционального индекса план меняется на:
-- Index Scan using idx_customers_email_lower on customers
--   Index Cond: (lower(email) = 'customer1500@example.com'::text)

